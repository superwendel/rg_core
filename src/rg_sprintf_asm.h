//
// USAGE:
//   #include "rg_sprintf_asm.h"
//   // All functions are static. On MSVC x64 AVX2, link the optional asm helpers
//   // (src/asm/sprintf/win_x64/rg_sprintf_asm_x64.asm) or define RG_SPRINTF_NO_ASM to force the C path.
//   // On non-MSVC platforms, define RG_SPRINTF_HAS_ASM in your build and link
//   // helper objects that provide the required symbols (see docs/rg_sprintf.md).
//
// OPTIONS:
//   #define RG_SPRINTF_NO_ASM      - Disable assembly helpers (fallback to C)
//   #define RG_SPRINTF_HAS_ASM     - Assembly helper symbols are available (build-system set)
//   #define RG_SPRINTF_ASM_UTOA_MIN_DIGITS 7 - Minimum digits to use asm u32 formatter
//   #define RG_SPRINTF_ASM_U64TOA_MIN_DIGITS 11 - Minimum digits to use asm u64 formatter
//   #define RG_SPRINTF_NO_LLONG_FASTPATH - Disable %lld fast path (benchmark toggle)
//   #define RG_SPRINTF_NO_SIMD     - Disable SIMD optimizations
//   #define RG_SPRINTF_SECURE      - Enable security checks (null checks, width/precision limits)
//   #define RG_SPRINTF_ASSERT(x)   - Custom assert macro
//
