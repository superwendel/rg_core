{
	if (n == 0) return 1;
#if defined(_MSC_VER)
	unsigned long idx;
#if defined(_M_X64) || defined(_M_ARM64)
	_BitScanReverse64(&idx, n);
#else
	if ((uint32_t)(n >> 32) != 0)
	{
		_BitScanReverse(&idx, (uint32_t)(n >> 32));
		idx += 32;
	}
	else
	{
		_BitScanReverse(&idx, (uint32_t)n);
	}
#endif
	int bits = (int)idx + 1;
#else
	int bits = 64 - __builtin_clzll(n);
#endif
	int t = (bits * 1233) >> 12;
	return t + (n >= rg_pow10_u64[t]);
}

